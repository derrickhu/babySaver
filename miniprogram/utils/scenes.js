function sceneName(gameKey, scene) {
  const key = String(scene || '').trim()
  if (!key) return '-'
  const named = (SCENE_LABELS[gameKey] || {})[key]
  if (named) return named
  if (/[\u4e00-\u9fff]/.test(key)) return key
  return key
}

